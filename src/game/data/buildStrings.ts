export function buildLevelName(bid: number, level: number): string {
    const safeLevel = Math.max(0, level);
    return BUILD_LEVEL_STRINGS[`${bid}_${safeLevel}`]?.title ?? `建筑${bid}`;
}

export function buildLevelDes(bid: number, level: number): string {
    const safeLevel = Math.max(0, level);
    return BUILD_LEVEL_STRINGS[`${bid}_${safeLevel}`]?.des ?? '';
}

export function itemName(itemId: number): string {
    return ITEM_STRINGS[String(itemId)]?.title ?? `物品${itemId}`;
}
